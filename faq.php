        <!-- FAQ 1 -->
        <div class="faq-item active">
          <div class="faq-header">
            <span class="faq-title">Is IELTS or TOEFL mandatory for African students?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            No. For English-taught programs in Belarus, state universities do not mandate IELTS or TOEFL for applicants whose high school education was conducted in English (such as Nigeria, Ghana, Kenya, Cameroon, South Africa, etc.). Your secondary school leaving certificate (e.g. WAEC, NECO, KCSE) serves as proof of English proficiency.
          </div>
        </div>

        <!-- FAQ 2 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">Are medical and engineering degrees from Belarus globally recognized?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            Yes, 100%. All partner medical universities (BSMU, VSMU, Grodno State Medical University) are state institutions listed in the World Health Organization (WHO) and FAIMER/WDOMS directories. Medical graduates qualify to sit for the USMLE (USA), PLAB/GMC (UK), AMC (Australia), MDCN (Nigeria), KMPDC (Kenya), and other national medical regulatory councils. Engineering graduates receive the European Bologna-compliant diploma supplement recognized across the EU.
          </div>
        </div>

        <!-- FAQ 3 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">What is an Official Study Invitation Letter, and how long does it take?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            The Official Invitation Letter is the legal document issued by the Ministry of Education and the Department of Citizenship and Migration in Belarus. It grants a foreign citizen the legal right to receive a student visa. It typically takes 7 to 14 business days to be processed and stamped by state migration authorities once your documents are approved by the university dean.
          </div>
        </div>

        <!-- FAQ 4 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">How does the visa process work for African students?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            Students from countries with a Belarusian Embassy (e.g. Nigeria, Egypt, Kenya) submit their passport with the Official Ministry Invitation, medical report, and educational documents for an entry visa stamp. For students in countries without a resident embassy, the Republic of Belarus provides an official Airport Entry Visa upon arrival at Minsk International Airport (MSQ), pre-cleared by our on-ground team. Study Partners coaches each student on immigration questions for a 98% approval record.
          </div>
        </div>

        <!-- FAQ 5 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">When and how is the university tuition fee paid?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            You do NOT pay tuition to random agents beforehand. Tuition fees are paid directly to the university's official state bank account or bursary department upon arrival in Belarus after completing campus medical registration and document verification. Most universities also allow split payments across the two academic semesters.
          </div>
        </div>

        <!-- FAQ 6 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">Are student dormitories guaranteed for international students?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            Yes. Every admitted student through Study Partners is allocated an official university hostel room prior to departure. Dormitories are furnished (bed, wardrobe, desk, heating, shared kitchen, hot water, high-speed Wi-Fi) and cost between $35 and $60 per month.
          </div>
        </div>

        <!-- FAQ 7 -->
        <div class="faq-item">
          <div class="faq-header">
            <span class="faq-title">Can international students work while studying in Belarus?</span>
            <svg class="faq-toggle-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>
          </div>
          <div class="faq-content">
            International students are permitted to take part-time work or internships during vacations and during the semester with university permission, especially in technology, research assistance, and language tutoring. However, due to rigorous academic schedules (particularly in Medicine and Engineering), we advise students to focus primarily on their coursework during the first academic year.
          </div>
        </div>

